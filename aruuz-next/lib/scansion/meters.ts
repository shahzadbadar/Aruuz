import type { Feet as FeetType } from './types';

export function afail(meter: string): string {
  let ft = '';
  for (const s of meter.split('+')) {
    for (const foot of s.split('/')) {
      for (let i = 0; i < FEET.length; i++) {
        if (foot === FEET[i]) ft += ' ' + FEET_NAMES[i];
      }
    }
  }
  return ft;
}

export function afailHindi(meterName: string): string {
  for (let i = 0; i < NUM_SPECIAL_METERS; i++) {
    if (meterName === SPECIAL_METER_NAMES[i]) return SPECIAL_METERS_AFAIL[i];
  }
  return '';
}

export function afail2(meter: string, code: string): FeetType[] {
  const met1 = meter.replace(/\//g, '');
  const met2 = met1.replace(/\+/g, '') + '-';
  const met3 = met1.replace(/\+/g, '-') + '-';
  const met4 = met1.replace(/\+/g, '-');
  const metOrig = met1.replace(/\+/g, '');

  const check = (pat: string): boolean => {
    if (pat.length !== code.length) return true;
    for (let j = 0; j < pat.length; j++) {
      const m = pat[j], c = code[j];
      if (m === '-' && c !== '-' && c !== 'x') return true;
      if (m === '=' && c !== '=' && c !== 'x') return true;
    }
    return false;
  };

  let mete = '';
  if (!check(metOrig)) mete = meter;
  if (!check(met2)) mete = meter + '-';
  if (!check(met3)) mete = meter.replace(/\+/g, '-+') + '-';
  if (!check(met4)) mete = meter.replace(/\+/g, '-+');

  const ft: FeetType[] = [];
  for (const s of mete.split('+')) {
    for (const foot of s.split('/')) {
      for (let i = 0; i < FEET.length; i++) {
        if (foot === FEET[i]) ft.push({ foot: FEET_NAMES[i], code: FEET[i] });
      }
    }
  }
  return ft;
}

export function rukn(code: string): string {
  const c = code.replace(/x/g, '=');
  for (let i = 0; i < FEET.length; i++) {
    if (c === FEET[i]) return FEET_NAMES[i];
  }
  return '';
}

export function meterIndex(metName: string): number[] {
  const lst: number[] = [];
  for (let i = 0; i < NUM_METERS; i++) {
    if (METER_NAMES[i] === metName) lst.push(i);
  }
  return lst;
}
